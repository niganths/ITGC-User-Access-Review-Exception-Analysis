CREATE DATABASE IF NOT EXISTS itgc_review;
USE itgc_review;



CREATE TABLE `employee_master` (
  `Emp_ID` VARCHAR(10) PRIMARY KEY,
  `Employee_Name` VARCHAR(100),
  `Department` VARCHAR(50),
  `Job_Title` VARCHAR(80),
  `Manager` VARCHAR(100),
  `Employment_Status` VARCHAR(20),
  `Hire_Date` DATE,
  `Termination_Date` DATE
);

CREATE TABLE `user_accounts` (
  `User_ID` VARCHAR(10) PRIMARY KEY,
  `Emp_ID_FK` VARCHAR(10),
  `Account_Name` VARCHAR(100),
  `System` VARCHAR(50),
  `Account_Type` VARCHAR(20),
  `Account_Status` VARCHAR(20),
  `Last_Login` DATE,
  `MFA_Enabled` VARCHAR(10),
  `Password_Last_Changed` DATE,
  `Identity_Type` VARCHAR(20)
);

CREATE TABLE `role_assignments` (
  `Assignment_ID` VARCHAR(10) PRIMARY KEY,
  `User_ID` VARCHAR(10) PRIMARY KEY,
  `Emp_ID` VARCHAR(10) PRIMARY KEY,
  `Role` VARCHAR(60),
  `System` VARCHAR(50),
  `Privilege_Level` VARCHAR(20),
  `Approval_Status` VARCHAR(20),
  `Assigned_Date` DATE
);

CREATE TABLE `sod_rules` (
  `Conflict_ID` VARCHAR(10) PRIMARY KEY,
  `Role_A` VARCHAR(60),
  `Role_B` VARCHAR(60),
  `Domain` VARCHAR(30),
  `Risk` VARCHAR(20),
  `Control_Objective` VARCHAR(150)
);

CREATE TABLE `access_matrix` (
  `Rule_ID` VARCHAR(10) PRIMARY KEY,
  `Job_Title` VARCHAR(80),
  `Permitted_Role` VARCHAR(60),
  `System` VARCHAR(50),
  `Access_Status` VARCHAR(20)
);

